function summarize(patients) {
  const n = patients.length
  const nz = (arr) => arr.filter((v) => v !== null && v !== undefined)
  const mean = (arr) => (arr.length ? arr.reduce((s, v) => s + v, 0) / arr.length : 0)
  const avgAge = mean(nz(patients.map((p) => p.age)))
  const diabetesPct = (patients.filter((p) => p.diabetes).length / n) * 100
  const avgSystolic = mean(nz(patients.map((p) => p.systolic)))
  const avgDiastolic = mean(nz(patients.map((p) => p.diastolic)))
  const avgPain = mean(nz(patients.map((p) => p.painScore)))
  const avgBmi = mean(nz(patients.map((p) => p.bmi)))
  const activityCounts = ACTIVITY_LEVELS.map(
    (lvl) => patients.filter((p) => p.activity === lvl).length,
  )
  return { n, avgAge, diabetesPct, avgSystolic, avgDiastolic, avgPain, avgBmi, activityCounts }
}

