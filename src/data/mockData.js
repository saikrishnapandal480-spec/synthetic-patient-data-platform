// --- Correlation matrices computed from real (synthetic-source) values ------
function pearson(xs, ys) {
  const n = Math.min(xs.length, ys.length)
  if (n < 3) return 0
  const mx = xs.reduce((s, v) => s + v, 0) / n
  const my = ys.reduce((s, v) => s + v, 0) / n
  let num = 0
  let dx = 0
  let dy = 0
  for (let i = 0; i < n; i++) {
    const a = xs[i] - mx
    const b = ys[i] - my
    num += a * b
    dx += a * a
    dy += b * b
  }
  const den = Math.sqrt(dx * dy)
  return den === 0 ? 0 : num / den
}

export const CORRELATION_FIELDS = ['Age', 'Diabetes', 'Systolic BP', 'Pain', 'BMI', 'Glucose']

const CORR_ACCESSORS = [
  (p) => p.age,
  (p) => (p.diabetes ? 1 : 0), // Yes/No → 1/0 for the calculation only
  (p) => p.systolic,
 (p) => p.painScore,
  (p) => p.bmi,
  (p) => p.glucose,
]

const CORR_MIN_ROWS = 3

// Pearson correlation matrix over the given patients. Values are real
// calculations — null cells (rendered as N/A) mean insufficient valid data
// (fewer than CORR_MIN_ROWS complete pairs or zero variance), never a guess.
export function computeCorrelationMatrix(patients, fields = CORRELATION_FIELDS) {
  const rows = Array.isArray(patients) ? patients : []
  return fields.map((_, i) =>
    fields.map((__, j) => {
      if (i === j) return 1
      const a = []
      const b = []
      for (const p of rows) {
        const av = CORR_ACCESSORS[i](p)
        const bv = CORR_ACCESSORS[j](p)
        if (av !== null && av !== undefined && bv !== null && bv !== undefined) {
          a.push(av)
          b.push(bv)
        }
      }
      if (a.length < CORR_MIN_ROWS) return null
      const r = pearson(a, b)
      // pearson returns 0 on zero variance — distinguish that from a real 0:
      // check variance directly on the first variable (a) as a guard.
      if (new Set(a).size < 2 || new Set(b).size < 2) return null
      return round2(r)
    }),
  )
}

