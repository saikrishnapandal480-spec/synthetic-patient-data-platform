// --- Phase 6: backend custom-cohort records → canonical frontend shape ------
// POST /api/cohort/generate returns {patient_id, age, gender, diabetes: Yes|No,
// blood_pressure: "sys/dia", activity_level, medication_adherence, pain_score,
// glucose, hba1c, bmi, source_donor_id}. This normalizes those records into the
// same shape the Cohort Builder's generator produces, so Dashboard, Synthetic
// Data, and Validation consume backend cohorts with zero page changes.
export function backendPatientsToCanonical(patients) {
  const ageGroupFor = (age) => {
    if (age <= 35) return '18–35'
    if (age <= 55) return '36–55'
    if (age <= 75) return '56–75'
    return '76+'
  }
  return patients.map((p, i) => {
    const [sys, dia] = String(p.blood_pressure || '0/0').split('/').map(Number)
    return {
      id: i,
      patientId: p.patient_id,
      name: `Synthetic Patient ${i + 1}`,
      age: p.age,
      gender: p.gender || 'Unknown',
      diabetes: p.diabetes === 'Yes' || p.diabetes === true,
      systolic: sys,
      diastolic: dia,
      painScore: p.pain_score,
      activity: p.activity_level,
      adherence: p.medication_adherence,
      bmi: p.bmi ?? null,
      glucose: p.glucose ?? null,
      hba1c: p.hba1c ?? null,
      ageGroup: ageGroupFor(p.age),
      sourceDonorId: p.source_donor_id || null,
      origin: 'backend-cohort',
    }
  })
}

