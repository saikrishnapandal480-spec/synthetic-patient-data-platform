// ---------------------------------------------------------------------------
// SH-405 synthetic generation layer.
//
// Extends (does not replace) the previous generator: patients are now
// bootstrap-resampled from the 140-patient Synthea source pool with light
// jitter, so source relationships (age↔BP, diabetes↔glucose/A1c,
// conditions↔age, pain↔condition burden) are inherited rather than invented.
// activity_level and medication_adherence are produced here — they do NOT
// exist in the source (see SOURCE_GAPS).
// ---------------------------------------------------------------------------
function deriveActivity(rand, age, conditionCount) {
  let w = { Sedentary: 0.18, Light: 0.3, Moderate: 0.32, Active: 0.2 }
  if (age >= 65) w = { Sedentary: w.Sedentary + 0.14, Light: w.Light + 0.06, Moderate: w.Moderate - 0.1, Active: w.Active - 0.1 }
  if (conditionCount >= 10) w = { Sedentary: w.Sedentary + 0.08, Light: w.Light + 0.04, Moderate: w.Moderate - 0.06, Active: w.Active - 0.06 }
  return weightedPick(rand, w)
}

function deriveAdherence(rand, age, conditionCount) {
  let w = { High: 0.55, Medium: 0.3, Low: 0.15 }
  if (age >= 75) w = { High: w.High - 0.08, Medium: w.Medium + 0.03, Low: w.Low + 0.05 }
  if (conditionCount >= 10) w = { High: w.High - 0.05, Medium: w.Medium + 0.02, Low: w.Low + 0.03 }
  return weightedPick(rand, w)
}

// TESTS ONLY — not imported by any page or state module. The application's
// real generator is the FastAPI backend (POST /api/cohort/generate).
export function generateSyntheticCohort(config) {
  const {
    count = 500,
    ageGroups = { '18–35': 20, '36–55': 35, '56–75': 32, '76+': 13 },
    diabetesPct = 20,
    highBpPct = 30,
    activity = 'Mirror source distribution',
  } = config
  const rand = mulberry32(1000 + count * 7 + diabetesPct * 13 + highBpPct * 29)

  const totalWeight = Object.values(ageGroups).reduce((s, w) => s + w, 0) || 1

  // Donor pools from the source sample (patients with a known age).
  const pool = SOURCE_PER_PATIENT.filter((p) => p.age !== null && p.age !== undefined)
  const diabeticPool = pool.filter((p) => p.has_diabetes)
  const nonDiabeticPool = pool.filter((p) => !p.has_diabetes)
  const highBpPool = pool.filter((p) => p.systolic_bp !== null && p.systolic_bp >= 140)
  const normalBpPool = pool.filter((p) => p.systolic_bp !== null && p.systolic_bp < 140)
  const poolMean = (arr, key) => {
    const vals = arr.map((p) => p[key]).filter((v) => v !== null && v !== undefined)
    return vals.length ? vals.reduce((s, v) => s + v, 0) / vals.length : null
  }

  const activityWeights =
    activity === 'Sedentary'
      ? { Sedentary: 0.55, Light: 0.25, Moderate: 0.15, Active: 0.05 }
      : activity === 'Light'
        ? { Sedentary: 0.25, Light: 0.4, Moderate: 0.25, Active: 0.1 }
        : activity === 'Moderate'
          ? { Sedentary: 0.15, Light: 0.28, Moderate: 0.38, Active: 0.19 }
          : activity === 'Active'
            ? { Sedentary: 0.05, Light: 0.18, Moderate: 0.35, Active: 0.42 }
            : null // 'Mirror source distribution' → derived per-patient below

  return Array.from({ length: count }, (_, i) => {
    // 1) Age group from the user's requested distribution…
    const group = weightedPick(
      rand,
      Object.fromEntries(Object.entries(ageGroups).map(([k, w]) => [k, w / totalWeight])),
    )
    const [lo, hi] = AGE_GROUP_RANGES[group]

    // 2) …then a source donor whose age fits that group (keeps age↔BP,
    //    age↔conditions coupling). Fall back to the nearest donors.
    let donors = pool.filter((p) => p.age >= lo && p.age <= hi)
    if (donors.length === 0) {
      const sorted = [...pool].sort(
        (a, b) => Math.abs(a.age - (lo + hi) / 2) - Math.abs(b.age - (lo + hi) / 2),
      )
      donors = sorted.slice(0, Math.min(5, sorted.length))
    }
    const donor = donors[Math.floor(rand() * donors.length)]

    // 3) Diabetes status per requested pct; glucose/A1c drawn from the
    //    matching source pool to preserve diabetes↔glucose even when the
    //    requested status differs from the donor's.
    const diabetes = rand() * 100 < diabetesPct
    const glyPool = diabetes
      ? (diabeticPool.length ? diabeticPool : pool)
      : (nonDiabeticPool.length ? nonDiabeticPool : pool)
    const hba1c = round1(
      clamp(
        (donor.hba1c ?? poolMean(glyPool, 'hba1c') ?? 5.7) + (rand() - 0.5) * 0.6,
        4,
        14,
      ),
    )
    const glucose = Math.round(
      clamp(
        (donor.glucose ?? poolMean(glyPool, 'glucose') ?? 95) + (rand() - 0.5) * 14,
        60,
        320,
      ),
    )

    // 4) BP status per requested pct; values resampled from the matching
    //    source pool (age-coupled, because pool members carry their own age).
    const highBp = rand() * 100 < highBpPct
    const bpPool = highBp ? (highBpPool.length ? highBpPool : pool) : (normalBpPool.length ? normalBpPool : pool)
    const sysDraw = (donor.systolic_bp ?? poolMean(bpPool, 'systolic_bp') ?? 125) + (rand() - 0.5) * 8
    // The user's requested BP mix wins: jitter must not cross the 140 threshold.
    const systolic = Math.round(highBp ? Math.max(140, sysDraw) : Math.min(139, sysDraw))
    const diastolic = Math.round(
      clamp((donor.diastolic_bp ?? poolMean(bpPool, 'diastolic_bp') ?? 80) + (rand() - 0.5) * 6, 50, 120),
    )

    // 5) Pain from the donor (pain↔condition burden preserved via resampling).
    const painScore = Math.round(
      clamp((donor.pain_score ?? 2) + Math.round((rand() - 0.5) * 2), 0, 10),
    )
    const bmi = round1(clamp((donor.bmi ?? 28) + (rand() - 0.5) * 1.6, 15, 55))

    // 6) DERIVED fields — not in the source; generated here as documented.
    const act = activityWeights
      ? weightedPick(rand, activityWeights)
      : deriveActivity(rand, donor.age, donor.condition_count)
    const adherence = deriveAdherence(rand, donor.age, donor.condition_count)

    return {
      id: i,
      patientId: `SYN-${String(50000 + i)}`,
      name: `${pick(rand, FIRST_NAMES)} ${pick(rand, LAST_NAMES)}`,
      age: Math.round(clamp(donor.age, lo, hi) === donor.age ? donor.age : Math.round(lo + rand() * (hi - lo))),
      gender: donor.gender || (rand() < 0.5 ? 'Female' : 'Male'),
      diabetes,
      systolic,
      diastolic,
      painScore,
      activity: act,
      adherence,
      bmi,
      glucose,
      hba1c,
      ageGroup: group,
      sourceDonorId: donor.patient_id,
    }
  })
}

