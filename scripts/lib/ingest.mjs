// ---------------------------------------------------------------------------
// SH-405 ingestion pipeline — Raw Dataset → Schema Mapping / Cleaning →
// SH-405 Canonical Dataset. Pure Node (no dependencies), so it can run as a
// build step and be unit-tested with `node --test`.
//
// Input : source_data/set100/csv/*.csv  (public SYNTHETIC Synthea export)
// Output: canonical SH-405 dataset (patients, clinical, longitudinal records)
//
// Synthea is a synthetic-data generator: all records are fabricated, so no
// real patient/PHI is used anywhere in this pipeline.
// ---------------------------------------------------------------------------

import fs from 'node:fs'
import path from 'node:path'

export const CANONICAL_SCHEMA_VERSION = 'sh405-canonical-1'

// LOINC codes we normalize from the Synthea observations table.
export const VITAL_CODES = {
  '8480-6': 'systolic_bp',
  '8462-4': 'diastolic_bp',
  '72514-3': 'pain_score',
  '2339-0': 'glucose',
  '4548-4': 'hba1c',
  '39156-5': 'bmi',
}

// --- Tiny RFC-4180 CSV parser (quotes, embedded commas, CRLF) ---------------
export function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let inQuotes = false

  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i += 1
        } else {
          inQuotes = false
        }
      } else {
        field += c
      }
    } else if (c === '"') {
      inQuotes = true
    } else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n') {
      row.push(field)
      field = ''
      if (row.length > 1 || (row.length === 1 && row[0] !== '')) rows.push(row)
      row = []
    } else if (c !== '\r') {
      field += c
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field)
    if (row.length > 1 || (row.length === 1 && row[0] !== '')) rows.push(row)
  }
  return rows
}

// --- Helpers ----------------------------------------------------------------
const toNum = (v) => {
  const n = Number(v)
  return Number.isFinite(n) ? n : null
}
const toIso = (v) => (v ? String(v).slice(0, 10) : null) // keep YYYY-MM-DD
const round1 = (x) => Math.round(x * 10) / 10
const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x))

export function calcAge(birthdate, ref) {
  if (!birthdate) return null
  const b = new Date(birthdate)
  if (Number.isNaN(b.getTime())) return null
  let age = ref.getFullYear() - b.getFullYear()
  const m = ref.getMonth() - b.getMonth()
  if (m < 0 || (m === 0 && ref.getDate() < b.getDate())) age -= 1
  return age
}

const GENDER_MAP = { M: 'Male', F: 'Female' }

